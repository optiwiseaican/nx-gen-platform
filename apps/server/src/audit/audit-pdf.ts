import type { ReportSection } from '@crescent/module-sdk';
import { renderReport } from '../reports/report-pdf';
import type { AuditEntry, AuditQuery } from './audit.service';

export interface AuditPdfContext {
  generatedBy: string;
  generatedById: string;
  platformInstanceId: string | null;
  chain: { valid: boolean; brokenAtSequence?: number };
}

const COLUMNS = [
  { title: '#', weight: 42 },
  { title: 'Time (UTC)', weight: 100 },
  { title: 'Action', weight: 180 },
  { title: 'Result', weight: 58 },
  { title: 'User', weight: 130 },
  { title: 'Record', weight: 130 },
  { title: 'Reason', weight: 130 },
];

function value(v: unknown): string {
  if (v === null || v === undefined) return '';
  return typeof v === 'object'
    ? JSON.stringify(v)
    : `${v as string | number | boolean}`;
}

const utc = (iso: string) => iso.replace('T', ' ').replace(/\.\d+Z$/, '');

function describeFilters(q: AuditQuery): string {
  const parts = [
    ['Action', q.action],
    ['User', q.actor],
    ['Category', q.category],
    ['Record', q.recordId],
    ['Result', q.result],
    ['From', q.from],
    ['Before', q.to],
  ].filter(([, v]) => v);
  return parts.length
    ? parts.map(([k, v]) => `${k}: ${v}`).join('; ')
    : 'None (complete trail)';
}

function toRow(e: AuditEntry): ReportSection['rows'][number] {
  const origin = [
    e.actorName ? `User ID: ${e.actor}` : '',
    e.machineName ? `Machine: ${e.machineName}` : '',
    e.ipAddress ? `IP: ${e.ipAddress}` : '',
    e.reason && e.errorCode ? `Error code: ${e.errorCode}` : '',
  ].filter(Boolean);
  const below = origin.length ? [origin.join(' · ')] : [];
  for (const [label, v] of [
    ['Old value', e.oldValue],
    ['New value', e.newValue],
    ['Details', e.details],
  ] as const) {
    const text = value(v);
    if (text) below.push(`${label}: ${text}`);
  }
  return {
    cells: [
      String(e.sequence),
      utc(e.occurredAt),
      `${e.category} · ${e.action}`,
      e.result,
      e.actorName ?? e.actor,
      [e.tableName, e.recordId].filter(Boolean).join(' · '),
      e.reason ?? e.errorCode ?? '',
    ],
    alertCell: e.result === 'FAILURE' ? 3 : undefined,
    below,
  };
}

/** Printable audit trail extract: oldest first, with old and new values in full. */
export function renderAuditPdf(
  entries: AuditEntry[],
  filters: AuditQuery,
  context: AuditPdfContext,
): Promise<Buffer> {
  const first = entries[0]?.sequence;
  const last = entries[entries.length - 1]?.sequence;
  return renderReport({
    title: 'NxGen Audit Trail Extract',
    summary: [
      { label: 'Generated (UTC)', value: utc(new Date().toISOString()) },
      {
        label: 'Generated by',
        value: `${context.generatedBy} (${context.generatedById})`,
      },
      {
        label: 'Platform instance',
        value: context.platformInstanceId ?? 'Not recorded',
      },
      { label: 'Filters', value: describeFilters(filters) },
      {
        label: 'Entries',
        value: entries.length
          ? `${entries.length} (sequence ${first} to ${last})`
          : 'None',
      },
      {
        label: 'Hash chain',
        value: context.chain.valid
          ? 'INTACT'
          : `BROKEN AT #${context.chain.brokenAtSequence}`,
        alert: !context.chain.valid,
      },
    ],
    note: 'Times are UTC, oldest entry first. The SHA-256 of this file is recorded in the audit trail under AUDIT_TRAIL_EXPORTED.',
    sections: [
      {
        columns: COLUMNS,
        rows: entries.map(toRow),
        empty: 'No entries match these filters.',
      },
    ],
  });
}
